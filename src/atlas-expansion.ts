import type { ChartPlace } from './atlas'

// Points measured on crops of the supplied illustration, displayed at 2048px wide.
// These are illustration coordinates, not claims of canonical geographic positions.
const crops: Record<string, [number, number, number]> = {
  totto: [2450, 3750, 2048], // Detail crop measured at native pixel size.
  north: [0, 0, 6200],
  west: [0, 4600, 6200],
  south: [7400, 4600, 6771],
  newworld: [0, 3450, 6050],
  paradise: [7600, 3550, 6571],
  east: [8200, 550, 5120],
}
type Entry = [name: string, x: number, y: number, description?: string, aliases?: string]
const officialSources: Record<string, string> = {
  Egghead: 'https://one-piece.com/story/egghead/index.html',
  Dressrosa: 'https://one-piece.com/story/dressrosa/index.html',
  Elbaph: 'https://one-piece.com/news/82672/index.html',
  'Sorbet Kingdom': 'https://one-piece.com/story/egghead/index.html',
  'Lulusia Kingdom': 'https://one-piece.com/story/egghead/index.html',
}
function group(crop: string, sea: string, entries: Entry[]): ChartPlace[] {
  const [originX, originY, width] = crops[crop]
  return entries.map(([name, x, y, description, aliases]) => ({
    id: name
      .toLowerCase()
      .replaceAll(/[^a-z0-9]+/g, '-')
      .replace(/-$/, ''),
    name,
    sea,
    x: ((originX + (x * width) / 2048) / 14171) * 3000,
    y: ((originY + (y * width) / 2048) / 7087) * 1500,
    description:
      description ??
      `${name} is labelled on this illustration in ${sea}. Its marker follows the supplied chart; the story does not establish exact world coordinates for every location.`,
    aliases,
    era: sea === 'New World' ? 'After the timeskip' : 'World lore',
    kind:
      /Kingdom|Country|Dukedom/.test(name) ||
      [
        'Dressrosa',
        'Elbaph',
        'Zou',
        'Totto Land',
        'Green Bit',
        'Flevance',
        'Momoiro Island',
      ].includes(name)
        ? 'Country'
        : /G-\d|Branch|Headquarters/.test(name)
          ? 'Marine base'
          : 'Island / place',
    position: 'chart',
    source: officialSources[name],
  }))
}

